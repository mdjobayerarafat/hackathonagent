interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("hh-lang");
    if (stored === "en" || stored === "zh") {
      setLangState(stored);
    } else if (navigator.language.toLowerCase().startsWith("zh")) {
      setLangState("zh");
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    window.localStorage.setItem("hh-lang", next);
  }, []);

  const toggleLang = useCallback(() => {
    setLangState((current) => {
      const next: Lang = current === "en" ? "zh" : "en";
      window.localStorage.setItem("hh-lang", next);
      return next;
    });
  }, []);

  const t = useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => {
      let value = dictionaries[lang][key] ?? key;
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          value = value.replaceAll(`{${name}}`, String(replacement));
        }
      }
      return value;
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, setLang, toggleLang, t }),
    [lang, setLang, toggleLang, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}

export function pickTitle(hackathon: Pick<Hackathon, "title" | "title_zh">, lang: Lang) {
  if (lang === "zh" && hackathon.title_zh?.trim()) return hackathon.title_zh;
  return hackathon.title;
}

export function phaseLabel(phase: string, t: I18nContextValue["t"]) {
  const key = `phase.${phase}` as TranslationKey;
  return dictionaries.en[key] ? t(key) : phase.replaceAll("_", " ");
}
